CREATE TABLE eventos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(200) NOT NULL,
    lugar           VARCHAR(200) NOT NULL,
    fecha_inicio    TIMESTAMPTZ  NOT NULL,
    fecha_creacion  TIMESTAMPTZ  NOT NULL
);

CREATE TABLE asientos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id  BIGINT         NOT NULL,
    codigo     VARCHAR(20)    NOT NULL,
    precio     NUMERIC(12, 2) NOT NULL,
    estado     VARCHAR(20)    NOT NULL,
    version    BIGINT         NOT NULL DEFAULT 0,

    CONSTRAINT fk_asientos_evento
        FOREIGN KEY (evento_id) REFERENCES eventos (id),

    CONSTRAINT uk_asientos_evento_codigo
        UNIQUE (evento_id, codigo),

    CONSTRAINT ck_asientos_precio
        CHECK (precio >= 0),

    CONSTRAINT ck_asientos_estado
        CHECK (estado IN ('DISPONIBLE', 'RETENIDO', 'VENDIDO'))
);

CREATE INDEX idx_asientos_evento_estado ON asientos (evento_id, estado);